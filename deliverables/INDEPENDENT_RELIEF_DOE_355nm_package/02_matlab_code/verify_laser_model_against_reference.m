function verification = verify_laser_model_against_reference(cfg, outputDir)
%VERIFY_LASER_MODEL_AGAINST_REFERENCE Check Ch.7 Gaussian-beam identities.
% Reference: Optical Design Using Excel, Sec. 7.1 and Sec. 7.3.
if ~exist(outputDir,'dir'); mkdir(outputDir); end

w0=cfg.laser.waistRadiusX;
m2=cfg.laser.M2X;
lambda=cfg.lambda;
zR=pi*w0^2/(m2*lambda);
z=zR;
W=w0*sqrt(1+(m2*lambda*z/(pi*w0^2))^2);
R=z*(1+(pi*w0^2/(m2*lambda*z))^2);
gouy=atan(m2*lambda*z/(pi*w0^2));
q=z+1i*zR;
inverseQ=1/q;

check={'Sec.7.1 waist amplitude at rho=w0'; ...
    'Sec.7.1 waist irradiance at rho=w0'; ...
    'Sec.7.1 waist wavefront curvature 1/R'; ...
    'Sec.7.3 measured-M2 Rayleigh range'; ...
    'Eq.7.24 W(zR)/W0'; ...
    'Eq.7.23 R(zR)/zR'; ...
    'Eq.7.4 generalized Gouy phase at zR'; ...
    'Eq.7.18a measured half divergence'; ...
    'Eq.7.22 real part of 1/Q'; ...
    'Eq.7.22 imaginary part of 1/Q'};
value=[exp(-1);exp(-2);0;zR;W/w0;R/zR;gouy; ...
    m2*lambda/(pi*w0);real(inverseQ);imag(inverseQ)];
expected=[exp(-1);exp(-2);0;cfg.laser.rayleighRangeX;sqrt(2);2; ...
    pi/4;cfg.laser.divergenceHalfAngleX;1/R; ...
    -m2*lambda/(pi*W^2)];
tolerance=[1e-14;1e-14;1e-14;1e-10;1e-12;1e-12;1e-12; ...
    1e-15;1e-15;1e-15];
pass=abs(value-expected)<=tolerance;
unit={'relative amplitude';'relative irradiance';'1/mm';'mm';'-';'-'; ...
    'rad';'rad';'1/mm';'1/mm'};
verification=table(check,value,expected,tolerance,unit,pass);
writetable(verification,fullfile(outputDir, ...
    'laser_model_reference_verification.csv'));
end
