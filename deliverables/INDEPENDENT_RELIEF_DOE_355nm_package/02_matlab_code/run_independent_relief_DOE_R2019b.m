function result = run_independent_relief_DOE_R2019b()
%RUN_INDEPENDENT_RELIEF_DOE_R2019B Main program for the self-designed DOE.
% Run this file in MATLAB R2019b.  It designs two manufacturable, quantized
% fused-silica relief surfaces, propagates their actual phase, generates the
% final 2-D irradiance and refreshes the package fabrication-data folder.

codeDir=fileparts(mfilename('fullpath'));
packageDir=fileparts(codeDir);
outputDir=fullfile(packageDir,'04_simulation_results','matlab_R2019b');
fabricationDir=fullfile(packageDir,'03_fabrication_data');
if ~exist(outputDir,'dir'); mkdir(outputDir); end
if ~exist(fabricationDir,'dir'); mkdir(fabricationDir); end

cfg=independent_relief_doe_config();
if ~strcmp(version('-release'),cfg.matlabRequired)
    error('laser_sim:WrongMATLAB','Required %s, running %s.', ...
        cfg.matlabRequired,version('-release'));
end

result.configuration=cfg;
result.laserReferenceVerification= ...
    verify_laser_model_against_reference(cfg,outputDir);
result.xDoe=simulate_independent_relief_doe(cfg,outputDir);
result.yModel=simulate_y_m2_gaussian_path(cfg,outputDir);
plot_independent_relief_doe_paths(cfg,outputDir);
result.designPass=result.xDoe.pass && result.yModel.pass && ...
    all(result.laserReferenceVerification.pass);

% Phase quantization and surface-reflection budget.  The scalar propagation
% itself is lossless; these values are engineering upper bounds before
% scatter, absorption, coating/process error and target-window spillover.
n=cfg.doe.refractiveIndex;
surfaceReflection=((n-1)/(n+1))^2;
quantizationTwo=cfg.doe.idealQuantizationEfficiency^2;
uncoatedSurfaceTransmission=(1-surfaceReflection)^4;
arResidualPerSurface=0.005;
arSurfaceTransmission=(1-arResidualPerSurface)^4;
result.efficiency.quantizationTwoDoe=quantizationTwo;
result.efficiency.uncoatedSurfaceTransmission=uncoatedSurfaceTransmission;
result.efficiency.uncoatedUpperBound= ...
    quantizationTwo*uncoatedSurfaceTransmission;
result.efficiency.ar05UpperBound=quantizationTwo*arSurfaceTransmission;

item={'Single-DOE 32-level phase quantization'; ...
    'Two-DOE phase quantization';'Single uncoated surface reflection'; ...
    'Four uncoated surfaces transmission'; ...
    'Two DOE, uncoated theoretical upper bound'; ...
    'Two DOE, 0.5% residual-R per surface upper bound'};
valuePercent=100*[cfg.doe.idealQuantizationEfficiency;quantizationTwo; ...
    surfaceReflection;uncoatedSurfaceTransmission; ...
    result.efficiency.uncoatedUpperBound;result.efficiency.ar05UpperBound];
note={'Phase-level upper bound';'Product of two phase-level factors'; ...
    'Normal-incidence Fresnel estimate';'Four air/silica interfaces'; ...
    'Excludes scatter, absorption and target spillover'; ...
    'Requires qualified 355 nm AR coating'};
writetable(table(item,valuePercent,note), ...
    fullfile(outputDir,'efficiency_budget.csv'));

metric={'First spherical expander magnification'; ...
    'X full 1/e^2 width';'X FWHM'; ...
    'X central-90 percent min/max uniformity'; ...
    'X uniformity limit';'Y full 1/e^2 width'; ...
    'Target mean X tilt';'Target curvature edge slope'; ...
    'X width change after 100 mm';'X width-change limit'; ...
    'Actual relief X cell pitch';'Design verification pass'};
value=[cfg.beamExpanderMagnification;result.xDoe.targetMeasuredWidth; ...
    result.xDoe.targetWidth50;100*result.xDoe.targetUniformity; ...
    100*cfg.acceptance.minUniformity;result.yModel.targetDiameter; ...
    1e6*result.xDoe.targetWave.meanAngle; ...
    1e6*result.xDoe.targetEdgeSlope;100*result.xDoe.targetWidthChange; ...
    100*cfg.acceptance.maxWidthChange;1e3*result.xDoe.doe.actualFeature; ...
    double(result.designPass)];
unit={'x';'mm';'mm';'%';'%';'mm';'urad';'urad';'%';'%';'um';'0/1'};
writetable(table(metric,value,unit), ...
    fullfile(outputDir,'independent_relief_doe_acceptance.csv'));

filesToCopy={'doe1_relief_cells.csv';'doe1_relief_profile.csv'; ...
    'doe2_relief_cells.csv';'doe2_relief_profile.csv'; ...
    'doe_binary_lithography_masks.csv'; ...
    'doe_binary_lithography_mask_preview.png'; ...
    'doe_fabrication_instructions.txt';'doe_fabrication_summary.csv'; ...
    'doe_relief_and_lithography_design.png'};
for fileIndex=1:numel(filesToCopy)
    copyfile(fullfile(outputDir,filesToCopy{fileIndex}), ...
        fullfile(fabricationDir,filesToCopy{fileIndex}));
end

fid=fopen(fullfile(outputDir,'execution_manifest.txt'),'w');
fprintf(fid,'Independent 355 nm relief DOE package\n');
fprintf(fid,'MATLAB version: %s\n',version);
fprintf(fid,'MATLAB release: %s\n',version('-release'));
fprintf(fid,'Execution date: %s\n',datestr(now,31));
fprintf(fid,'Proprietary vendor phase used: 0\n');
fprintf(fid,'Laser: %s, exit waist, M2X/M2Y=%.6f/%.6f\n', ...
    cfg.laser.coherence,cfg.laser.M2X,cfg.laser.M2Y);
fprintf(fid,'DOE material/index: %s / %.12f\n', ...
    cfg.doe.material,cfg.doe.refractiveIndex);
fprintf(fid,'DOE levels/masks: %d/%d\n', ...
    cfg.doe.quantizationLevels,cfg.doe.maskCount);
fprintf(fid,'First spherical expander: %.6fx (allowed %.1f-%.1fx)\n', ...
    cfg.beamExpanderMagnification,cfg.beamExpanderMagnificationRange(1), ...
    cfg.beamExpanderMagnificationRange(2));
fprintf(fid,'DOE1-DOE2 path: %.6f mm free space, no intermediate optic\n', ...
    cfg.layout.zDOE2-cfg.layout.zDOE1);
fprintf(fid,'X width: %.9f mm\n',result.xDoe.targetMeasuredWidth);
fprintf(fid,'X central-90%% min/max uniformity: %.9f %%\n', ...
    100*result.xDoe.targetUniformity);
fprintf(fid,'Y width: %.9f mm\n',result.yModel.targetDiameter);
fprintf(fid,'Target mean X tilt: %.9f urad\n', ...
    1e6*result.xDoe.targetWave.meanAngle);
fprintf(fid,'Target curvature edge slope: %.9f urad\n', ...
    1e6*result.xDoe.targetEdgeSlope);
fprintf(fid,'X width change after %.3f mm: %.9f %%\n', ...
    cfg.acceptance.propagationCheckDistance,100*result.xDoe.targetWidthChange);
fprintf(fid,'Design verification pass: %d\n',result.designPass);
fclose(fid);

save(fullfile(outputDir,'independent_relief_doe_result.mat'), ...
    'result','-v7.3');
end
