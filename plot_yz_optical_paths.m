function layoutTable = plot_yz_optical_paths(cfg,vendor,inhouse,outputDir)
%PLOT_YZ_OPTICAL_PATHS Annotated physical YZ paths with spherical expanders.
layouts={makeLayout(vendor,'Vendor'),makeLayout(inhouse,'In-house')};
drawSingle(layouts{1},'Vendor ST-426-I-Y-A - YZ optical layout', ...
    fullfile(outputDir,'vendor_yz_optical_path.png'));
drawSingle(layouts{2},'In-house two-DOE collimated mapper - YZ optical layout', ...
    fullfile(outputDir,'inhouse_yz_optical_path.png'));
fig=figure('Visible','off','Color','w','Position',[50 50 1550 900]);
subplot(2,1,1); drawAxes(layouts{1}); title('Vendor ST-426-I-Y-A - YZ plane')
subplot(2,1,2); drawAxes(layouts{2}); title('In-house two-DOE collimated mapper - YZ plane')
print(fig,fullfile(outputDir,'two_solution_yz_optical_paths.png'),'-dpng','-r180');
close(fig)
layoutTable=[layouts{1}.table;layouts{2}.table];
writetable(layoutTable,fullfile(outputDir,'yz_optical_layout.csv'));

    function L=makeLayout(solution,solutionName)
        p=cfg.layout;
        if isfield(solution,'collimated')
            z=[p.zLaser p.zExpander1L1 p.zExpander1L2 ...
                p.zExpander2L1 p.zExpander2L2 p.zInhouseDOE1 ...
                p.zFinalLens p.zTarget];
            ids={'LASER';'SBE1';'SBE2';'YBE1';'YBE2';'DOE1';'YFL';'DOE2/TGT'};
            axisPower={'-';'XY';'XY';'Y';'Y';'X phase';'Y';'X phase'};
            focalY=[Inf p.fExpander1L1 p.fExpander1L2 ...
                p.fExpander2L1 p.fExpander2L2 Inf cfg.finalYFocalLength Inf];
            aperture=[NaN 6 15 15 15 cfg.finalYLensClearAperture ...
                cfg.finalYLensClearAperture 15];
        else
            z=[p.zLaser p.zExpander1L1 p.zExpander1L2 p.zDOE ...
                p.zExpander2L1 p.zExpander2L2 p.zXCompressorL1 ...
                solution.xCompressorL2Z p.zXFinalLens p.zFinalLens p.zTarget];
            ids={'LASER';'SBE1';'SBE2';'DOE';'YBE1';'YBE2'; ...
                'CXC1';'CXC2';'XFL';'YFL';'TARGET'};
            axisPower={'-';'XY';'XY';'X phase';'Y';'Y';'X';'X';'X';'Y';'-'};
            focalY=[Inf p.fExpander1L1 p.fExpander1L2 Inf ...
                p.fExpander2L1 p.fExpander2L2 Inf Inf Inf cfg.finalYFocalLength Inf];
            aperture=[NaN 6 15 15 15 cfg.finalYLensClearAperture ...
                NaN NaN cfg.finalYLensClearAperture NaN];
        end
        if isfield(solution,'collimated')
            description={'355 nm TEM00 laser'; ...
                'First optic: rotationally symmetric negative expander lens'; ...
                'Rotationally symmetric positive expander lens, nominal 6x'; ...
                'Y-only negative cylindrical expander lens'; ...
                'Y-only positive cylindrical expander lens'; ...
                'Inverse-designed X DOE, no Y power'; ...
                'Y-only f=100 mm focusing cylinder'; ...
                'Terminal X phase corrector, no Y power'};
        else
            description={'355 nm TEM00 laser'; ...
                'First optic: rotationally symmetric negative expander lens'; ...
                'Rotationally symmetric positive expander lens, nominal 6x'; ...
                'Line phase DOE, no refractive Y power'; ...
                'Y-only negative cylindrical expander lens'; ...
                'Y-only positive cylindrical expander lens'; ...
                'X-only angular compressor lens 1, no Y power'; ...
                'X-only angular compressor lens 2, no Y power'; ...
                'X-only Fourier cylinder, no Y power'; ...
                'Last lens: Y-only fY=100 mm cylinder'; ...
                'Final 1.5 mm by 1.0 um target'};
        end

        d0=cfg.laserDiameter;
        d1=cfg.doeBeamDiameter;
        d2=cfg.finalYBeamDiameter;
        [za,ra]=constantSegment(0,p.zExpander1L1,d0/2);
        [zb,rb]=linearSegment(p.zExpander1L1,p.zExpander1L2,d0/2,d1/2);
        [zc,rc]=constantSegment(p.zExpander1L2,p.zExpander2L1,d1/2);
        [zd,rd]=linearSegment(p.zExpander2L1,p.zExpander2L2,d1/2,d2/2);
        [ze,re]=constantSegment(p.zExpander2L2,p.zFinalLens,d2/2);
        zf=linspace(p.zFinalLens,p.zTarget,180);
        waist=cfg.targetYWidth/2;
        zR=pi*waist^2/(cfg.M2*cfg.lambda);
        rf=waist*sqrt(1+((p.zTarget-zf)/zR).^2);
        rf=rf*(d2/2)/rf(1); rf(end)=waist;
        L.z=[za zb(2:end) zc(2:end) zd(2:end) ze(2:end) zf(2:end)];
        L.r=[ra rb(2:end) rc(2:end) rd(2:end) re(2:end) rf(2:end)];
        L.zComponents=z; L.ids=ids; L.axisPower=axisPower;
        L.zTarget=p.zTarget; L.solutionName=solutionName;
        L.table=table(repmat({solutionName},numel(z),1),ids(:),z(:), ...
            axisPower,focalY(:),aperture(:),description, ...
            'VariableNames',{'solution','elementID','z_mm','powerAxis', ...
            'focalLengthY_mm','suggestedClearAperture_mm','description'});
    end

    function drawSingle(L,titleText,fileName)
        fig=figure('Visible','off','Color','w','Position',[30 30 1700 760]);
        drawAxes(L); title(titleText)
        print(fig,fileName,'-dpng','-r180'); close(fig)
    end

    function drawAxes(L)
        fill([L.z fliplr(L.z)],[L.r -fliplr(L.r)],[0.82 0.91 1], ...
            'EdgeColor','none'); hold on
        plot(L.z,L.r,'b-','LineWidth',1.8); plot(L.z,-L.r,'b-','LineWidth',1.8)
        plot([0 L.zTarget],[0 0],'k--','LineWidth',0.8)
        ymax=1.12*max(L.r);
        for ii=1:numel(L.zComponents)
            isXOnly=strcmp(L.axisPower{ii},'X') || strcmp(L.axisPower{ii},'X phase');
            style='k-'; if isXOnly; style='k:'; end
            lw=1; if strcmp(L.ids{ii},'TARGET'); lw=2.3; end
            plot([L.zComponents(ii) L.zComponents(ii)],[-ymax ymax],style,'LineWidth',lw)
            text(L.zComponents(ii),1.02*ymax,sprintf('%s\nZ=%.1f', ...
                L.ids{ii},L.zComponents(ii)),'Rotation',35,'FontSize',7.3)
        end
        p=cfg.layout;
        info=sprintf(['SBE1 spherical f=%.1f, SBE2 spherical f=%.1f mm (6x)\n' ...
            'YBE1 cylinder fY=%.1f, YBE2 cylinder fY=%.2f mm (%.3fx)\n' ...
            'YFL cylinder fY=100 mm, input D_Y=%.2f mm, suggested CA>=%.2f mm\n' ...
            'CXC1/CXC2, XFL and DOE have no Y optical power'], ...
            p.fExpander1L1,p.fExpander1L2,p.fExpander2L1,p.fExpander2L2, ...
            p.mExpander2,cfg.finalYBeamDiameter,cfg.finalYLensClearAperture);
        text(15,-0.90*ymax,info,'FontSize',7.8,'BackgroundColor','w', ...
            'EdgeColor',[0.5 0.5 0.5])
        text(L.zTarget,-0.14*ymax,'Y full 1/e^2 = 1.0 um', ...
            'HorizontalAlignment','right','FontWeight','bold')
        xlabel('Optical-axis position Z (mm)'); ylabel('Y (mm)'); grid on
        xlim([0 1.025*L.zTarget]); ylim([-1.32*ymax 1.32*ymax])
    end

    function [z,r]=constantSegment(z1,z2,radius)
        z=linspace(z1,z2,80); r=radius*ones(size(z));
    end
    function [z,r]=linearSegment(z1,z2,r1,r2)
        z=linspace(z1,z2,120); r=r1+(r2-r1)*(z-z1)/(z2-z1);
    end
end
